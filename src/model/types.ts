/**
 * Canonical project data model (format `bite-project`, formatVersion 1).
 *
 * This file is the single source of truth for the persisted shape of a project. Everything that is
 * saved, exported or imported is one of these types. See docs/PROJECT_FORMAT.md for the prose spec.
 *
 * Conventions (see docs/ARCHITECTURE.md §Coordinates):
 *  - Right-handed, Y-up, units are metres. The ground is y = 0.
 *  - Positions in metres, rotations in degrees with Euler order 'YXZ', scale is a per-axis multiplier.
 *  - Object forward is local -Z. Positive yaw (rotation.y) turns counter-clockwise seen from above.
 *  - Object transforms are local to their parent (or world when parentId is null).
 */

export const PROJECT_FORMAT = 'bite-project' as const;
export const PROJECT_FORMAT_VERSION = 1 as const;

export type Vec3 = [number, number, number];

/** A value stored in a variable or produced by a reporter block. */
export type Value = number | string | boolean;

/** Hex colour string "#rrggbb". */
export type HexColor = string;

export type ObjectKind = 'cube' | 'sphere' | 'cylinder' | 'plane' | 'group' | 'light' | 'camera';

export const OBJECT_KINDS: readonly ObjectKind[] = ['cube', 'sphere', 'cylinder', 'plane', 'group', 'light', 'camera'];

export type LightKind = 'directional' | 'point';

export type BodyType = 'none' | 'static' | 'dynamic' | 'kinematic';
export const BODY_TYPES: readonly BodyType[] = ['none', 'static', 'dynamic', 'kinematic'];

export type ColliderShape = 'auto' | 'box' | 'sphere' | 'cylinder';
export const COLLIDER_SHAPES: readonly ColliderShape[] = ['auto', 'box', 'sphere', 'cylinder'];

export interface Transform {
  position: Vec3;
  /** Degrees, Euler order YXZ. */
  rotation: Vec3;
  scale: Vec3;
}

export interface MaterialSettings {
  color: HexColor;
  /** 0 (invisible) .. 1 (opaque). */
  opacity: number;
  /** 0 .. 1 */
  metalness: number;
  /** 0 .. 1 */
  roughness: number;
}

export interface PhysicsSettings {
  bodyType: BodyType;
  /** Collider shape; 'auto' derives it from the object kind. */
  shape: ColliderShape;
  /** kilograms, used by dynamic bodies. Must be > 0. */
  mass: number;
  /** 0 .. 2, Coulomb friction coefficient. */
  friction: number;
  /** 0 .. 1, bounciness. */
  restitution: number;
  /** Multiplier of the scene gravity for this body. */
  gravityScale: number;
  /** When true the body does not tumble (rotation locked on all axes). */
  lockRotation: boolean;
}

export interface LightSettings {
  kind: LightKind;
  /** Relative intensity, 0 .. 10. */
  intensity: number;
}

export interface CameraSettings {
  /** Vertical field of view in degrees. */
  fov: number;
}

export type VariableScope = 'global' | 'local';

export interface Variable {
  id: string;
  name: string;
  /** Initial value. The runtime works on a copy that is restored on Reset. */
  value: Value;
}

export interface BlockNode {
  id: string;
  opcode: string;
  /** Dropdown / text / colour fields that are not value inputs. */
  fields?: Record<string, string | number | boolean>;
  /** Value inputs: a literal (shadow value) or a nested reporter/boolean block. */
  inputs?: Record<string, InputValue>;
  /** Statement inputs (C-block bodies): ordered stacks of blocks. */
  stacks?: Record<string, BlockNode[]>;
}

export type InputValue = string | number | boolean | BlockNode;

export interface Script {
  id: string;
  /** Position of the top-left corner in the code workspace (for layout persistence). */
  position: { x: number; y: number };
  /** Top-level stack. nodes[0] is the hat/event block that starts the script. */
  nodes: BlockNode[];
}

export interface SoundAsset {
  id: string;
  name: string;
  /** Lower-case file extension without dot: wav, mp3, ogg, m4a, flac, aac, webm. */
  extension: string;
  /** MIME type, e.g. audio/wav. */
  mimeType: string;
  byteLength: number;
  /** Duration in seconds when known (set on import after decoding). */
  durationSec: number | null;
  /** Built-in sounds were generated by the app and are stored like any other asset. */
  builtIn: boolean;
}

export interface SceneObject {
  id: string;
  name: string;
  kind: ObjectKind;
  parentId: string | null;
  visible: boolean;
  transform: Transform;
  material: MaterialSettings;
  physics: PhysicsSettings;
  light: LightSettings | null;
  camera: CameraSettings | null;
  variables: Variable[];
  scripts: Script[];
}

export interface StageCameraSettings {
  position: Vec3;
  target: Vec3;
  fov: number;
}

export interface ProjectSettings {
  /** Gravity vector in m/s². Default [0, -9.81, 0]. */
  gravity: Vec3;
  backgroundColor: HexColor;
  shadows: boolean;
  stageCamera: StageCameraSettings;
  /** Object whose camera is used during play, or null for the stage camera. */
  activeCameraId: string | null;
  /** Initial master volume, 0..100 percent. */
  masterVolume: number;
}

export interface StageData {
  id: 'stage';
  name: string;
  /** Global variables are visible to every target. */
  variables: Variable[];
  scripts: Script[];
}

export interface Project {
  format: typeof PROJECT_FORMAT;
  formatVersion: typeof PROJECT_FORMAT_VERSION;
  /** Version of the application that last wrote the file (informational). */
  appVersion: string;
  id: string;
  name: string;
  createdAt: string;
  updatedAt: string;
  settings: ProjectSettings;
  stage: StageData;
  objects: SceneObject[];
  /** Broadcast message names available to the project. */
  messages: string[];
  sounds: SoundAsset[];
}

/** Key codes accepted by the key events and key blocks. */
export const SUPPORTED_KEYS = [
  'any',
  'space',
  'enter',
  'up arrow',
  'down arrow',
  'left arrow',
  'right arrow',
  'shift',
  ...'abcdefghijklmnopqrstuvwxyz'.split(''),
  ...'0123456789'.split(''),
] as const;

export type SupportedKey = (typeof SUPPORTED_KEYS)[number];
